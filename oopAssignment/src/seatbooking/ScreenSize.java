package seatbooking;

public class ScreenSize {
	private int width;
	private int height;
	
	public ScreenSize(){
		width = 0;
		height = 0;
	}
	public int getWidth(){
		return width;
	}
	public int getHeight(){
		return height;
	}
	public void setWidth(int width){
		this.width = width; 
	}
	public void setHeight(int height){
		this.height = height; 
	}
}
